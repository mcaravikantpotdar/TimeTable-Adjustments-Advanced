import { DAY_NAMES } from '../config/constants.js';
import { state, adjustState, getFullSub, getFullTea } from '../state/store.js';
import { sanitize, formatTime, setPrintOrientation } from '../utils/helpers.js';
import { getRuleDetails } from '../core/clashEngine.js';
import { showToast } from '../ui/notifications.js';

export function printTeacherDailySlips() {
    if (adjustState.dayIndex === -1) {
        showToast("Invalid day for printing.", "error");
        return;
    }

    setPrintOrientation('portrait');
    const layout = document.getElementById('printLayout');

    const [pY, pM, pD] = adjustState.dateStr.split('-');
    const months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
    const dateStrClean = `${parseInt(pD)} ${months[parseInt(pM) - 1]} ${pY} (${DAY_NAMES[adjustState.dayIndex].toUpperCase()})`;

    let presentTeachers = state.registry.teachers.filter(t => !adjustState.absent.includes(t.s));
    let html = '';

    presentTeachers.forEach(tea => {
        let dailyPeriods = [];

        state.rules.forEach(r => {
            if (r.tea === tea.s && r.days[adjustState.dayIndex]) {
                const det = getRuleDetails(r);
                if (det) {
                    dailyPeriods.push({ ...r, ...det, type: 'REGULAR' });
                }
            }
        });

        Object.entries(adjustState.covers).forEach(([rId, subCode]) => {
            if (subCode === tea.s) {
                const cr = state.rules.find(x => x.id === rId);
                if (cr) {
                    const det = getRuleDetails(cr);
                    if (det) {
                        dailyPeriods.push({ ...cr, ...det, type: 'COVER', originalTea: cr.tea });
                    }
                }
            }
        });

        if (dailyPeriods.length === 0) return;

        dailyPeriods.sort((a, b) => a.s - b.s);

        html += `<div class="page-break" style="margin-bottom: 40px; page-break-inside: avoid;">`;
        html += `<div style="border: 2px solid #000; padding: 20px; border-radius: 12px; font-family: 'Inter Tight', sans-serif;">`;
        html += `<div style="text-align:center; border-bottom: 2px solid #000; padding-bottom: 10px; margin-bottom: 15px;">`;
        html += `<h1 style="font-size:20px; font-weight:900; margin:0; text-transform:uppercase;">DAILY DOCKET: ${sanitize(tea.f)}</h1>`;
        html += `<h2 style="font-size:12px; font-weight:700; margin:4px 0 0 0; color:#475569;">${dateStrClean}</h2>`;
        html += `</div>`;

        html += `<table style="width:100%; border-collapse: collapse; text-align: left;">`;
        html += `<thead><tr style="border-bottom: 2px solid #cbd5e1;"><th style="padding: 8px 4px; font-size:11px;">TIME</th><th style="padding: 8px 4px; font-size:11px;">CLASS</th><th style="padding: 8px 4px; font-size:11px;">SUBJECT</th><th style="padding: 8px 4px; font-size:11px;">STATUS</th></tr></thead><tbody>`;

        dailyPeriods.forEach(p => {
            const isCover = p.type === 'COVER';
            const rowBg = isCover ? 'background-color: #fef08a;' : '';
            const statusText = isCover ? `COVERING (${getFullTea(p.originalTea)})` : 'REGULAR';
            const statusStyle = isCover ? 'color: #b45309; font-weight: 900;' : 'color: #475569; font-weight: 700;';

            html += `<tr style="${rowBg} border-bottom: 1px solid #e2e8f0;">
                <td style="padding: 10px 4px; font-size: 12px; font-weight: 900;">${formatTime(p.s)} - ${formatTime(p.e)}<br><span style="font-size:10px; font-weight: normal; color: #64748b;">${sanitize(p.pName)}</span></td>
                <td style="padding: 10px 4px; font-size: 14px; font-weight: 900;">${sanitize(p.class)}</td>
                <td style="padding: 10px 4px; font-size: 12px; font-weight: 700;">${getFullSub(p.sub)}</td>
                <td style="padding: 10px 4px; font-size: 10px; ${statusStyle}">${statusText}</td>
            </tr>`;
        });

        html += `</tbody></table>`;
        html += `<div style="margin-top: 20px; text-align: right; font-size: 10px; font-weight: 700; color: #94a3b8;">Generated by Academic Architect</div>`;
        html += `</div></div>`;
    });

    if (!html) {
        showToast("No active periods to print for today.", "info");
        return;
    }

    layout.innerHTML = html;

    const origTitle = document.title;
    document.title = "Daily Slips - " + dateStrClean;

    layout.classList.add('is-printing');
    window.print();
    layout.classList.remove('is-printing');

    document.title = origTitle;
}
